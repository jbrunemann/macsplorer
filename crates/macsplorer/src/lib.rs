use eframe::egui;

/// The desktop program.
#[cfg(not(target_os = "android"))]
pub fn run() -> eframe::Result {
    #[cfg(unix)]
    locale::install();
    let start = std::env::args_os()
        .nth(1)
        .map(std::path::PathBuf::from)
        .filter(|p| p.is_dir())
        .or_else(dirs::home_dir)
        .unwrap_or_else(|| "/".into());

    let prefs = macsplorer_core::preferences::Preferences::load();
    let mut viewport = egui::ViewportBuilder::default()
        .with_title("Macsplorer")
        // Wayland and X11 match the window to its .desktop file by this.
        .with_app_id("macsplorer")
        // The size the last window was resized to, else Macsplorer's own.
        .with_inner_size(prefs.window.unwrap_or([1000.0, 680.0]))
        .with_min_inner_size(macsplorer_core::preferences::MIN_WINDOW)
        // The Windows 2000 caption and frame are drawn by the app. A
        // borderless window is the only kind macOS doesn't round, and it
        // keeps edge resizing and minimize (winit sets those style bits).
        .with_decorations(false)
        .with_icon(app_icon());
    // A window opened with File > New Window cascades from the one before it.
    if let Some((pos, size)) = platform::inherited_frame() {
        viewport = viewport.with_position(pos).with_inner_size(size);
    }
    let options = eframe::NativeOptions { viewport, ..Default::default() };
    eframe::run_native("Macsplorer", options, Box::new(move |cc| Ok(Box::new(start_app(cc, start, &prefs)))))
}

/// The Android app: `crates/macsplorer-android` hands its activity in. The
/// home folder is the shared storage ("Internal storage"), so `~` and the
/// known folders are the ones the user sees in other apps; the settings stay
/// in the app's private folder.
#[cfg(target_os = "android")]
pub fn run_android(android_app: android_activity::AndroidApp) {
    android_logger::init_once(android_logger::Config::default().with_tag("macsplorer").with_max_level(log::LevelFilter::Info));
    android::set_app(android_app.clone());
    let home = android::shared_storage().unwrap_or_else(|| "/storage/emulated/0".into());
    // SAFETY: nothing else is running yet, so nothing reads the environment concurrently.
    unsafe {
        std::env::set_var("HOME", &home);
        if let Some(private) = android_app.internal_data_path() {
            std::env::set_var("XDG_CONFIG_HOME", private.join("config"));
            std::env::set_var("XDG_CACHE_HOME", private.join("cache"));
        }
        // GL through ANGLE is slow and some emulators lack it.
        if std::env::var_os("WGPU_BACKEND").is_none() {
            std::env::set_var("WGPU_BACKEND", "vulkan");
        }
    }
    locale::install();
    // Without "All files access" only media files show: the system page to allow it comes first.
    if !android::all_files_access() {
        android::request_all_files_access();
    }
    let prefs = macsplorer_core::preferences::Preferences::load();
    let options = eframe::NativeOptions { android_app: Some(android_app), ..Default::default() };
    let run = eframe::run_native("Macsplorer", options, Box::new(move |cc| Ok(Box::new(start_app(cc, home, &prefs)))));
    if let Err(e) = run {
        log::error!("{e}");
    }
}

/// The window's app, set up from the saved preferences.
fn start_app(cc: &eframe::CreationContext, start: std::path::PathBuf, prefs: &macsplorer_core::preferences::Preferences) -> app::Explorer {
    cc.egui_ctx.set_theme(egui::Theme::Light);
    theme::install(&cc.egui_ctx);
    theme::set_dark(&cc.egui_ctx, prefs.dark);
    // The app's Text Size steps replace egui's 10% zoom keys.
    cc.egui_ctx.options_mut(|o| o.zoom_with_keyboard = false);
    cc.egui_ctx.set_zoom_factor(prefs.zoom);
    // Before anything looks for git, so the lookup can start from where it was.
    macsplorer_core::git::remember(prefs.git.clone());
    #[cfg(target_os = "macos")]
    native_drag::install(cc);
    let mut app = app::Explorer::new(cc.egui_ctx.clone(), start);
    app.restore_preferences(prefs);
    app
}

/// The app icon, also used as the Dock icon when running outside a bundle.
/// Generated by `cargo run -p make-icon`.
#[cfg(not(target_os = "android"))]
fn app_icon() -> egui::IconData {
    eframe::icon_data::from_png_bytes(include_bytes!("../../../assets/icon.png")).expect("embedded icon is a valid PNG")
}
